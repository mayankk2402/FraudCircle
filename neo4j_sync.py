"""
Neo4j Sync Module for FraudCircle
Supports both local Neo4j (neo4j://127.0.0.1:7687) and AuraDB Cloud (neo4j+s://...)
"""

import pandas as pd
import json

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(BASE_DIR, "data")


def generate_cypher_for_scenario(nodes_df, edges_df, scenario_tag):
    """Generate Cypher CREATE statements for a given scenario."""
    sc_edges = edges_df[edges_df["scenario_tag"] == scenario_tag]
    edge_nodes = set(sc_edges["source"]).union(set(sc_edges["target"]))
    sc_nodes = nodes_df[(nodes_df["scenario_tag"] == scenario_tag) | (nodes_df["node_id"].isin(edge_nodes))]

    cypher_lines = []
    cypher_lines.append(f"// FraudCircle - Cypher Export for: {scenario_tag}")
    cypher_lines.append(f"// Generated by FraudCircle Neo4j Sync Module\n")

    # CREATE nodes
    for _, row in sc_nodes.iterrows():
        nid = row["node_id"].replace("-", "_").replace(" ", "_")
        label = row["node_type"]
        props = {
            "node_id": row["node_id"],
            "name": str(row.get("name", "")),
            "account_subtype": str(row.get("account_subtype", "")),
            "account_age_days": int(row.get("account_age_days", 0)),
            "kyc_verified": int(row.get("kyc_verified", 0)),
            "ground_truth_fraud": int(row.get("ground_truth_fraud", 0)),
            "scenario_tag": scenario_tag
        }
        props_str = ", ".join([f'{k}: "{v}"' if isinstance(v, str) else f"{k}: {v}"
                               for k, v in props.items()])
        cypher_lines.append(f"CREATE ({nid}:{label} {{{props_str}}})")

    cypher_lines.append("")

    # CREATE relationships
    for _, row in sc_edges.iterrows():
        src = row["source"].replace("-", "_").replace(" ", "_")
        tgt = row["target"].replace("-", "_").replace(" ", "_")
        rel_type = row["edge_type"]
        amt = row.get("amount", 0)
        ts = str(row.get("timestamp", ""))
        cypher_lines.append(
            f'CREATE ({src})-[:{rel_type} {{amount: {amt}, timestamp: "{ts}"}}]->({tgt})'
        )

    return "\n".join(cypher_lines)


def generate_match_query_for_scenario(scenario_tag):
    """Generate a MATCH query to view a scenario in Neo4j Browser."""
    return (
        f"// View {scenario_tag} subgraph\n"
        f"MATCH (n {{scenario_tag: '{scenario_tag}'}})\n"
        f"OPTIONAL MATCH path = (n)-[r]-(m {{scenario_tag: '{scenario_tag}'}})\n"
        f"RETURN path, n, r, m\n"
        f"LIMIT 500"
    )


def sync_to_neo4j(uri, username, password, nodes_df, edges_df, scenario_tag=None):
    """Sync data to Neo4j instance (local or AuraDB)."""
    try:
        from neo4j import GraphDatabase
    except ImportError:
        return {"success": False, "error": "neo4j driver not installed. Run: pip install neo4j"}

    try:
        driver = GraphDatabase.driver(uri, auth=(username, password))
        with driver.session() as session:
            # Clear existing data for scenario (if specified)
            if scenario_tag:
                session.run(
                    "MATCH (n {scenario_tag: $tag}) DETACH DELETE n",
                    tag=scenario_tag
                )
                filt_nodes = nodes_df[nodes_df["scenario_tag"] == scenario_tag]
                filt_edges = edges_df[edges_df["scenario_tag"] == scenario_tag]
            else:
                session.run("MATCH (n) DETACH DELETE n")
                filt_nodes = nodes_df
                filt_edges = edges_df

            # Create nodes
            for _, row in filt_nodes.iterrows():
                session.run(
                    f"CREATE (n:{row['node_type']} $props)",
                    props=row.to_dict()
                )

            # Create edges
            for _, row in filt_edges.iterrows():
                session.run(
                    f"MATCH (a {{node_id: $src}}), (b {{node_id: $tgt}}) "
                    f"CREATE (a)-[r:{row['edge_type']} {{amount: $amt, timestamp: $ts}}]->(b)",
                    src=row["source"], tgt=row["target"],
                    amt=row.get("amount", 0), ts=str(row.get("timestamp", ""))
                )

        driver.close()
        return {"success": True, "nodes": len(filt_nodes), "edges": len(filt_edges)}
    except Exception as e:
        return {"success": False, "error": str(e)}


def export_all_cypher(output_path=None):
    """Export all scenarios as a single Cypher script file."""
    nodes_df = pd.read_csv(os.path.join(DATA_DIR, "Nodes_FraudCircle.csv"))
    edges_df = pd.read_csv(os.path.join(DATA_DIR, "Edges_FraudCircle.csv"))

    scenarios = nodes_df["scenario_tag"].unique()
    all_cypher = ["// FraudCircle - Complete Cypher Export", "// All Scenarios\n"]

    for sc in scenarios:
        all_cypher.append(generate_cypher_for_scenario(nodes_df, edges_df, sc))
        all_cypher.append("\n")

    full_text = "\n".join(all_cypher)
    if output_path is None:
        output_path = os.path.join(DATA_DIR, "FraudCircle_Neo4j_Export.cypher")

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(full_text)

    print(f"[OK] Cypher export saved: {output_path}")
    return output_path


if __name__ == "__main__":
    print("[*] FraudCircle Neo4j Sync Module")
    path = export_all_cypher()
    print(f"[DONE] Exported to: {path}")
